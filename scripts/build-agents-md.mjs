/**
 * Generate the GLOBAL AGENTS.md content (repo-agnostic): agent table + the
 * shared instruction bodies. This is the content installed into the user's
 * global config dir as AGENTS.md.
 *
 * @param {Array<{ file: string, name: string, body: string, agents?: string[] }>} instructions
 * @param {{ sha: string, date: string }} git - Git info from readGitInfo()
 * @returns {string}
 */
export function generateGlobalAgentsMd(instructions, git = readGitInfo()) {
  const sharedInstructions = instructions.filter(
    (instr) => !instr.agents || instr.agents.includes('*'),
  )
  const sections = [
    MANAGED_BEGIN,
    GENERATED_BY,
    '<!-- Source of truth: src/instructions/*.instructions.md + the static sections in this script. -->',
    versionLine('global', git),
    '',
    GLOBAL_HEADER.trimEnd(),
    INSTRUCTIONS_PREAMBLE,
    '',
  ]
  for (const instr of sharedInstructions) {
    // The section marker below already carries the title; drop a duplicated
    // leading H1 from the instruction body (agent prompts keep it intact).
    const body = instr.body.replace(/^\s*#\s[^\n]*\n+/, '')
    sections.push(
      `<!-- Source: src/instructions/${instr.file} -->`,
      `## ${instr.name}`,
      '',
      body.trimEnd(),
      '',
    )
  }
  sections.push(MANAGED_END)
  return `${sections.join('\n').trimEnd()}\n`
}

/**
 * Generate the PROJECT AGENTS.md content (repo-specific setup only). Shared
 * rules deliberately live in the global artifact so a session never pays for
 * the same rule twice.
 *
 * @param {{ sha: string, date: string }} git - Git info from readGitInfo()
 * @returns {string}
 */
export function generateProjectAgentsMd(git = readGitInfo()) {
  const sections = [
    MANAGED_BEGIN,
    GENERATED_BY,
    '<!-- Source of truth: project sections in scripts/build-agents-md.mjs. -->',
    versionLine('project', git),
    '',
    PROJECT_HEADER.trimEnd(),
    MANAGED_END,
  ]
  return `${sections.join('\n').trimEnd()}\n`
}

// ---------------------------------------------------------------------------
// Managed-region writer — shared by the installer (scripts/install/opencode.mjs)
// and the postinstall freshness sync (scripts/sync-artifacts.mjs).
// ---------------------------------------------------------------------------

/**
 * Write an AGENTS.md artifact conservatively:
 *
 *   - missing target          → write generated content ('created')
 *   - managed region present  → replace ONLY the region; any user content
 *                               around it is preserved ('updated' when the
 *                               file is pure managed content, 'merged' when
 *                               foreign content was kept)
 *   - legacy generated file   → the whole file is machine-generated per its
 *                               own header; upgrade in place ('upgraded')
 *   - foreign file            → never clobber: append the managed region
 *                               below the user's content ('merged')
 *
 * Byte-compare idempotent: identical content returns 'skipped' untouched.
 *
 * @param {string} filePath - Destination AGENTS.md path
 * @param {string} generated - Generated artifact content (incl. sentinels)
 * @param {boolean} [dryRun=false] - Do not write when true
 * @returns {'created' | 'skipped' | 'updated' | 'upgraded' | 'merged'}
 */
export function writeAgentsMdManaged(filePath, generated, dryRun = false, recorder = null) {
  assertPathWithin(dirname(filePath), filePath)
  assertNoSymlinkAncestors(filePath)
  const existing = existsSync(filePath) ? readFileSync(filePath, 'utf8') : null
  if (existing === null) {
    if (!dryRun) {
      assertNoSymlinkAncestors(dirname(filePath))
      mkdirSync(dirname(filePath), { recursive: true })
      assertNoSymlinkAncestors(filePath)
      writeFileSync(filePath, generated, 'utf8')
      verifyRegularFile(filePath, generated)
    }
    recordChange(
      {
        path: filePath,
        action: ACTIONS.CREATE,
        bytes: Buffer.byteLength(generated, 'utf8'),
        outputFingerprint: fingerprintOutput(generated),
      },
      recorder,
    )
    return 'created'
  }
  if (existing === generated) {
    recordChange(
      {
        path: filePath,
        action: ACTIONS.UNCHANGED,
        bytes: Buffer.byteLength(existing, 'utf8'),
        outputFingerprint: fingerprintOutput(existing),
      },
      recorder,
    )
    return 'skipped'
  }

  const begin = existing.indexOf(MANAGED_BEGIN)
  const end = existing.indexOf(MANAGED_END)
  if (begin !== -1 && end !== -1 && end > begin) {
    const before = existing.slice(0, begin)
    const after = existing.slice(end + MANAGED_END.length)
    const next = `${before}${generated}${after}`
    if (next === existing) {
      recordChange(
        {
          path: filePath,
          action: ACTIONS.UNCHANGED,
          bytes: Buffer.byteLength(existing, 'utf8'),
          outputFingerprint: fingerprintOutput(existing),
        },
        recorder,
      )
      return 'skipped'
    }
    if (!dryRun) {
      assertNoSymlinkAncestors(filePath)
      writeFileSync(filePath, next, 'utf8')
      verifyRegularFile(filePath, next)
    }
    recordChange(
      {
        path: filePath,
        action: ACTIONS.UPDATE,
        bytes: Buffer.byteLength(next, 'utf8'),
        outputFingerprint: fingerprintOutput(next),
      },
      recorder,
    )
    return before.trim() === '' && after.trim() === '' ? 'updated' : 'merged'
  }

  if (existing.startsWith(GENERATED_BY)) {
    // Legacy format: the header declares the whole file machine-generated.
    if (!dryRun) {
      assertNoSymlinkAncestors(filePath)
      writeFileSync(filePath, generated, 'utf8')
      verifyRegularFile(filePath, generated)
    }
    recordChange(
      {
        path: filePath,
        action: ACTIONS.UPDATE,
        bytes: Buffer.byteLength(generated, 'utf8'),
        outputFingerprint: fingerprintOutput(generated),
      },
      recorder,
    )
    return 'upgraded'
  }

  // Foreign content: preserve it verbatim and append the managed region.
  const separator = existing.endsWith('\n') ? '\n' : '\n\n'
  const payload = `${existing}${separator}${generated}`
  if (!dryRun) {
    assertNoSymlinkAncestors(filePath)
    writeFileSync(filePath, payload, 'utf8')
    verifyRegularFile(filePath, payload)
  }
  recordChange(
    {
      path: filePath,
      action: ACTIONS.UPDATE,
      bytes: Buffer.byteLength(payload, 'utf8'),
      outputFingerprint: fingerprintOutput(payload),
    },
    recorder,
  )
  return 'merged'
}

const GENERATED_AGENT_BLOCK =
  /\n?<!-- Pantheon selective instructions: generated -->[\s\S]*?<!-- \/Pantheon selective instructions -->\n?/g

/**
 * Render the agent-specific instruction set into the supported agent prompt.
 * The shared rules remain in AGENTS.md; file globs are retained as scope
 * guidance and are never used as agent selectors.
 *
 * @param {string} agentName - Canonical agent name from the prompt filename
 * @param {string} prompt - Canonical source agent prompt
 * @param {Array<{ file: string, name: string, body: string, applyTo?: string | null,
 *   agents?: string[], fallback?: string | null }>} instructions
 * @returns {string}
 */
export function generateAgentPrompt(agentName, prompt, instructions = readInstructions()) {
  const basePrompt = prompt.replace(GENERATED_AGENT_BLOCK, '').trimEnd()
  const selected = instructions.filter(
    (instr) => instr.agents && !instr.agents.includes('*') && instr.agents.includes(agentName),
  )
  if (selected.length === 0) {
    return [
      basePrompt,
      '',
      '<!-- Pantheon selective instructions: generated -->',
      'No agent-specific instructions are assigned; follow the shared rules in AGENTS.md.',
      '<!-- /Pantheon selective instructions -->',
      '',
    ].join('\n')
  }

  const sections = selected.map((instr) => {
    const scope = instr.applyTo
      ? `\n\n> Apply only when a target workspace file matches \`${instr.applyTo}\`.`
      : ''
    const fallback =
      instr.fallback === 'shared'
        ? '\n\n> For work outside this scope, use the shared rules in AGENTS.md.'
        : ''
    return [
      `<!-- Source: src/instructions/${instr.file} -->`,
      `## ${instr.name}${scope}`,
      '',
      `${instr.body.trimEnd()}${fallback}`,
    ].join('\n')
  })
  return [
    basePrompt,
    '',
    '<!-- Pantheon selective instructions: generated -->',
    sections.join('\n\n'),
    '<!-- /Pantheon selective instructions -->',
    '',
  ].join('\n')
}

/**
 * Copy agent prompts with scoped instructions embedded in each actual prompt.
 * Used by both init and postinstall sync so the installed runtime receives the
 * same selection without a per-turn injection hook.
 *
 * @param {string} sourceDir - Canonical src/agents directory
 * @param {string} targetDir - OpenCode agents directory
 * @param {boolean} dryRun - Do not write when true
 * @param {boolean} existingOnly - Refresh installed prompts without adding missing agents
 * @param {(change: object) => void} [recorder] - optional change recorder for --dry-run preview
 * @returns {{ created: number, skipped: number }}
 */
export function copyAgentPrompts(
  sourceDir,
  targetDir,
  dryRun = false,
  existingOnly = false,
  recorder = null,
) {
  assertNoSymlinkAncestors(targetDir)
  const instructions = readInstructions()
  if (!dryRun && !existingOnly) {
    assertNoSymlinkAncestors(targetDir)
    mkdirSync(targetDir, { recursive: true })
    assertNoSymlinkAncestors(targetDir)
  }
  let created = 0
  let skipped = 0
  for (const file of readdirSync(sourceDir)
    .filter((entry) => entry.endsWith('.md'))
    .sort()) {
    if (file.toLowerCase() === 'readme.md') continue
    const sourcePath = join(sourceDir, file)
    if (!statSync(sourcePath).isFile()) continue
    const agentName = file.replace(/\.md$/, '')
    const output = generateAgentPrompt(agentName, readFileSync(sourcePath, 'utf8'), instructions)
    const targetPath = join(targetDir, file)
    assertPathWithin(targetDir, targetPath)
    assertNoSymlinkAncestors(targetPath)
    if (existingOnly && !existsSync(targetPath)) continue
    const existing = existsSync(targetPath) ? readFileSync(targetPath, 'utf8') : null
    if (existing === output) {
      skipped++
      if (isRecording(recorder)) {
        recordChange(
          {
            path: targetPath,
            action: ACTIONS.UNCHANGED,
            bytes: Buffer.byteLength(output, 'utf8'),
            outputFingerprint: fingerprintOutput(output),
          },
          recorder,
        )
      }
    } else {
      if (!dryRun) {
        assertNoSymlinkAncestors(targetPath)
        writeFileSync(targetPath, output, 'utf8')
        verifyRegularFile(targetPath, output)
      }
      created++
      if (isRecording(recorder)) {
        recordChange(
          {
            path: targetPath,
            action: existing === null ? ACTIONS.CREATE : ACTIONS.UPDATE,
            bytes: Buffer.byteLength(output, 'utf8'),
            outputFingerprint: fingerprintOutput(output),
          },
          recorder,
        )
      }
    }
  }
  return { created, skipped }
}

/**
 * Count LF-delimited logical lines without assuming a trailing newline.
 *
 * @param {string} content - File content
 * @returns {number}
 */
export function logicalLineCount(content) {
  if (content.length === 0) return 0
  const separators = content.match(/\n/g)?.length ?? 0
  return separators + (content.endsWith('\n') ? 0 : 1)
}

// ---------------------------------------------------------------------------
// CLI entry point
// ---------------------------------------------------------------------------

function main() {
  const checkOnly = process.argv.includes('--check')
  const instructions = readInstructions()
  const sharedCount = instructions.filter(
    (instr) => !instr.agents || instr.agents.includes('*'),
  ).length
  const global = generateGlobalAgentsMd(instructions)
  const project = generateProjectAgentsMd()

  if (checkOnly) {
    const stale = []
    const existingGlobal = existsSync(AGENTS_GLOBAL_MD_PATH)
      ? readFileSync(AGENTS_GLOBAL_MD_PATH, 'utf8')
      : ''
    const existingProject = existsSync(AGENTS_MD_PATH) ? readFileSync(AGENTS_MD_PATH, 'utf8') : ''
    if (stripVersionLine(existingGlobal) !== stripVersionLine(global)) {
      stale.push('AGENTS.global.md')
    }
    if (stripVersionLine(existingProject) !== stripVersionLine(project)) {
      stale.push('AGENTS.md')
    }
    if (stale.length > 0) {
      console.error(
        `❌ ${stale.join(' and ')} ${
          stale.length > 1 ? 'are' : 'is'
        } stale — run: node scripts/build-agents-md.mjs`,
      )
      process.exit(1)
    }
    console.log(
      `✅ AGENTS.md and AGENTS.global.md are up to date (${sharedCount} shared instruction sections)`,
    )
    return
  }

  writeFileSync(AGENTS_GLOBAL_MD_PATH, global, 'utf8')
  writeFileSync(AGENTS_MD_PATH, project, 'utf8')
  verifyRegularFile(AGENTS_GLOBAL_MD_PATH, global)
  verifyRegularFile(AGENTS_MD_PATH, project)
  console.log(
    `✅ Generated AGENTS.md (${logicalLineCount(project)} lines) + AGENTS.global.md ` +
      `(${logicalLineCount(global)} lines, ${sharedCount} shared instruction sections)`,
  )
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main()
}
