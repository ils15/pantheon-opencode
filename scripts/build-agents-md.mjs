#!/usr/bin/env node
/**
 * build-agents-md.mjs — Generate BOTH AGENTS.md artifacts from canonical sources.
 *
 * AGENTS.md files are instruction files BOTH OpenCode V1 and V2 load (V1
 * auto-discovers them, V2 loads them explicitly; the `instructions` config
 * key is accepted-but-ignored by V2). Every session pays for global AND
 * project AGENTS.md content, so a single duplicated file is paid twice per
 * session. To keep the payload disjoint (beta-10 latency slice, phase 1),
 * this script emits TWO artifacts in ONE pass over the same sources:
 *
 *   AGENTS.md         — repo-specific setup only (build commands, sandbox
 *                       rules, conventions). Loaded by sessions in THIS repo.
 *   AGENTS.global.md  — repo-agnostic content only (agent table + shared
 *                       instruction bodies embedded under a `## <name>`
 *                       section marker). The installer/sync emits this into
 *                       the user's global config dir as AGENTS.md.
 *
 * Zero overlap: each rule lives in exactly one artifact. Agent-scoped
 * instruction bodies are still rendered into only their matching agent
 * prompt. The instruction files remain the source of truth; both artifacts
 * are committed build artifacts, never hand-edited. Each carries a version
 * header (generated-at + short git sha) so a stale artifact is detectable;
 * `--check` ignores that volatile line and byte-compares everything else.
 *
 * Usage:
 *   node scripts/build-agents-md.mjs            # write both artifacts
 *   node scripts/build-agents-md.mjs --check    # exit 1 if either is stale
 *
 * No runtime dependencies (Node >= 18, stdlib only). Idempotent: running it
 * twice produces byte-identical output (the version header is derived from
 * git, not the wall clock).
 */
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ACTIONS, fingerprintOutput, isRecording, recordChange } from './install/plan.mjs'
import { assertNoSymlinkAncestors, assertPathWithin, verifyRegularFile } from './install/verify.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
export const ROOT = join(__dirname, '..')
const INSTRUCTIONS_DIR = join(ROOT, 'src', 'instructions')
export const AGENTS_MD_PATH = join(ROOT, 'AGENTS.md')
export const AGENTS_GLOBAL_MD_PATH = join(ROOT, 'AGENTS.global.md')

// ---------------------------------------------------------------------------
// Managed region — both artifacts are fully machine-generated; the sentinels
// let the installer refresh the region while preserving any user content
// around it (conservative migration: non-managed content is never deleted).
// ---------------------------------------------------------------------------
export const MANAGED_BEGIN =
  '<!-- pantheon:generated:begin — Pantheon-managed region; regenerated on install/upgrade, never edit inside -->'
export const MANAGED_END =
  '<!-- pantheon:generated:end — user content outside this region is preserved verbatim -->'

/** Header comment every generator version has emitted, old and new. */
const GENERATED_BY = '<!-- Generated by scripts/build-agents-md.mjs — do not edit directly. -->'
const VERSION_LINE_RE = /^<!-- pantheon:agents-md v2 artifact=(?:global|project) [^\n]*-->$/gm

/**
 * Normalize the volatile version line so `--check` can byte-compare content
 * across commits (the sha/generated-at intentionally lag HEAD by one commit).
 *
 * @param {string} content - Artifact content
 * @returns {string} Content with the version line reduced to a fixed stub
 */
export function stripVersionLine(content) {
  return content.replace(VERSION_LINE_RE, '<!-- pantheon:agents-md v2 -->')
}

/**
 * Short git sha + commit date of HEAD — deterministic per commit, so the
 * version header never breaks byte-determinism while still dating artifacts.
 * Falls back to "unknown" outside a git worktree (npm tarball installs).
 *
 * @param {string} [root] - Repository root to run git in
 * @returns {{ sha: string, date: string }}
 */
export function readGitInfo(root = ROOT) {
  try {
    const opts = { cwd: root, encoding: 'utf8' }
    return {
      sha: execFileSync('git', ['rev-parse', '--short=7', 'HEAD'], opts).trim(),
      date: execFileSync('git', ['log', '-1', '--format=%cI'], opts).trim(),
    }
  } catch {
    return { sha: 'unknown', date: 'unknown' }
  }
}

/**
 * The `pantheon:agents-md` version line embedded in every artifact.
 *
 * @param {'global' | 'project'} artifact - Which artifact the line stamps
 * @param {{ sha: string, date: string }} git - Git info from readGitInfo()
 * @returns {string}
 */
function versionLine(artifact, git) {
  return `<!-- pantheon:agents-md v2 artifact=${artifact} generated-at=${git.date} sha=${git.sha} -->`
}

