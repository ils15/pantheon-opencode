#!/usr/bin/env node
/**
 * Build (or check) the ESM bundle the published decision-router CLI imports.
 *
 * Node refuses to strip TypeScript types for files under `node_modules`
 * (`ERR_UNSUPPORTED_NODE_MODULES_TYPE_STRIPPING`), so an installed package
 * cannot import `src/pantheon/local-decision-budget.ts` directly. The CLI is the
 * documented administrative interface, so this bundle is committed and shipped
 * as plain JavaScript; `--check` fails when it drifts from the TypeScript
 * source.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { build } from 'esbuild'

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..')
const ENTRY = join(ROOT, 'src', 'pantheon', 'local-decision-budget.ts')
const OUTPUT = join(ROOT, 'scripts', 'decision-router-budget.mjs')
const BANNER = `// Generated by scripts/build-decision-router.mjs from src/pantheon/local-decision-budget.ts.
// The published CLI cannot import TypeScript from node_modules, so it imports
// this prebuilt ESM bundle instead. Do not edit: run \`npm run build:decision-router\`.`

/** Bundle the budget ledger exactly as the CLI consumes it. */
export async function buildDecisionRouterBudget({ outfile = OUTPUT } = {}) {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    outfile,
    write: false,
    banner: { js: BANNER },
    legalComments: 'none',
    sourcemap: false,
    logLevel: 'silent',
  })
  const [output] = result.outputFiles
  if (!output) throw new Error('esbuild produced no bundle')
  return output.text
}

const invokedDirectly =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href

if (invokedDirectly) {
  const check = process.argv.includes('--check')
  const bundle = await buildDecisionRouterBudget()
  if (check) {
    const current = (() => {
      try {
        return readFileSync(OUTPUT, 'utf8')
      } catch {
        return ''
      }
    })()
    if (current !== bundle) {
      console.error(
        'scripts/decision-router-budget.mjs is stale. Run `npm run build:decision-router` and commit the result.',
      )
      process.exitCode = 1
    }
  } else {
    writeFileSync(OUTPUT, bundle)
    console.log('Wrote scripts/decision-router-budget.mjs')
  }
}
