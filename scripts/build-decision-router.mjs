#!/usr/bin/env node
/**
 * Build (or check) the ESM bundles the published decision-router CLI imports.
 *
 * Node refuses to strip TypeScript types for files under `node_modules`
 * (`ERR_UNSUPPORTED_NODE_MODULES_TYPE_STRIPPING`), so an installed package
 * cannot import `src/pantheon/*.ts` directly. The CLI is the documented
 * administrative interface, so these bundles are committed and shipped as plain
 * JavaScript; `--check` fails when any of them drifts from its TypeScript source.
 *
 * Three entries, one output each:
 *   - `local-decision-budget.ts` → the transactional ledger (caps/period writes);
 *   - `v2-decision-budget.ts`    → the separated cap/period/ledger read surface;
 *   - `v2-decision-egress.ts`    → the opt-in-only egress posture (default off).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { build } from 'esbuild'

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..')

const BANNER = `// Generated by scripts/build-decision-router.mjs. The published CLI cannot
// import TypeScript from node_modules, so it imports this prebuilt ESM bundle
// instead. Do not edit: run \`npm run build:decision-router\`.`

/** Every bundle the CLI consumes, in build order. */
export const DECISION_ROUTER_BUNDLES = Object.freeze([
  Object.freeze({
    name: 'ledger',
    entry: join(ROOT, 'src', 'pantheon', 'local-decision-budget.ts'),
    output: join(ROOT, 'scripts', 'decision-router-budget.mjs'),
  }),
  Object.freeze({
    name: 'v2-budget',
    entry: join(ROOT, 'src', 'pantheon', 'v2-decision-budget.ts'),
    output: join(ROOT, 'scripts', 'decision-router-v2-budget.mjs'),
  }),
  Object.freeze({
    name: 'v2-egress',
    entry: join(ROOT, 'src', 'pantheon', 'v2-decision-egress.ts'),
    output: join(ROOT, 'scripts', 'decision-router-v2-egress.mjs'),
  }),
])

async function bundle({ entry, output }) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    outfile: output,
    write: false,
    banner: { js: BANNER },
    legalComments: 'none',
    sourcemap: false,
    logLevel: 'silent',
  })
  const [built] = result.outputFiles
  if (!built) throw new Error(`esbuild produced no bundle for ${entry}`)
  return built.text
}

/** Bundle the budget ledger exactly as the CLI consumes it. */
export async function buildDecisionRouterBudget({ outfile } = {}) {
  const [ledger] = DECISION_ROUTER_BUNDLES
  return bundle({ entry: ledger.entry, output: outfile ?? ledger.output })
}

/** Bundle the separated V2 budget read surface. */
export async function buildDecisionRouterV2Budget({ outfile } = {}) {
  const v2Budget = DECISION_ROUTER_BUNDLES[1]
  return bundle({ entry: v2Budget.entry, output: outfile ?? v2Budget.output })
}

/** Bundle the V2 egress posture surface. */
export async function buildDecisionRouterV2Egress({ outfile } = {}) {
  const v2Egress = DECISION_ROUTER_BUNDLES[2]
  return bundle({ entry: v2Egress.entry, output: outfile ?? v2Egress.output })
}

/** Build every bundle; returns `[{ name, output, text }]`. */
export async function buildAllDecisionRouterBundles() {
  const built = []
  for (const target of DECISION_ROUTER_BUNDLES) {
    built.push({ name: target.name, output: target.output, text: await bundle(target) })
  }
  return built
}

const invokedDirectly =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href

if (invokedDirectly) {
  const check = process.argv.includes('--check')
  const built = await buildAllDecisionRouterBundles()
  let stale = 0
  for (const target of built) {
    if (check) {
      const current = (() => {
        try {
          return readFileSync(target.output, 'utf8')
        } catch {
          return ''
        }
      })()
      if (current !== target.text) {
        stale += 1
        console.error(
          `scripts/${target.output.split('/').pop()} is stale. Run \`npm run build:decision-router\` and commit the result.`,
        )
      }
    } else {
      writeFileSync(target.output, target.text)
      console.log(`Wrote scripts/${target.output.split('/').pop()}`)
    }
  }
  if (stale > 0) process.exitCode = 1
}
