/**
 * instruction-golden.test.mjs — structural evals for the instruction artifacts.
 *
 * Golden positive/negative cases over the REAL generators (no model calls):
 * where a block must appear, where it must NOT, and the exceptions. These run
 * in the regular node tier (gated by tests/eval/*.mjs in test:node); the
 * model-in-the-loop track stays behind docs/reference/offline-evaluation.md.
 */
import assert from 'node:assert/strict'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { test } from 'node:test'
import { fileURLToPath } from 'node:url'
import {
  generateAgentPrompt,
  generateGlobalAgentsMd,
  generateProjectAgentsMd,
  logicalLineCount,
  MANAGED_BEGIN,
  MANAGED_END,
  readInstructions,
  writeAgentsMdManaged,
} from '../../scripts/build-agents-md.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')

test('the managed region carves around user content and never clobbers it', () => {
  const dir = mkdtempSync(join(tmpdir(), 'pantheon-eval-carve-'))
  const path = join(dir, 'AGENTS.md')
  // The generator owns the sentinels: writeAgentsMdManaged writes the payload
  // verbatim and carves by finding the sentinels in the EXISTING content.
  const mkGenerated = (body) =>
    `${MANAGED_BEGIN}\n<!-- Generated by scripts/build-agents-md.mjs — do not edit directly. -->\n${body}\n${MANAGED_END}\n`
  try {
    // A foreign (user-owned) file: the region is appended below, content kept.
    writeFileSync(path, '# My notes\n')
    writeAgentsMdManaged(path, mkGenerated('GENERATED-V1'))
    let after = readFileSync(path, 'utf8')
    assert.ok(after.startsWith('# My notes\n'), 'user content must stay on top')
    assert.equal(after.split(MANAGED_BEGIN).length - 1, 1, 'exactly one begin sentinel')
    assert.equal(after.split(MANAGED_END).length - 1, 1, 'exactly one end sentinel')
    assert.ok(after.includes('GENERATED-V1'))

    // A regeneration swaps ONLY the region; user content survives verbatim.
    writeAgentsMdManaged(path, mkGenerated('GENERATED-V2'))
    after = readFileSync(path, 'utf8')
    assert.ok(after.startsWith('# My notes\n'))
    assert.ok(after.includes('GENERATED-V2'))
    assert.ok(!after.includes('GENERATED-V1'), 'stale generated body must be replaced')
    assert.equal(after.split(MANAGED_BEGIN).length - 1, 1)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
})

test('shared instructions land in the global artifact and never in the project one', () => {
  const instructions = readInstructions()
  const shared = instructions.filter((i) => !i.agents || i.agents.includes('*'))
  assert.ok(shared.length > 0, 'the fixture expects at least one shared instruction')
  const global = generateGlobalAgentsMd(instructions)
  const project = generateProjectAgentsMd()
  for (const instr of shared) {
    // Mirror the generator: the global artifact drops a duplicated leading H1
    // and renders `## <name>` as the section header.
    const bodyNoH1 = instr.body.replace(/^\s*#\s[^\n]*\n+/, '')
    const signature = bodyNoH1
      .split('\n')
      .find((l) => l.trim().length > 0)
      .slice(0, 60)
    assert.ok(global.includes(signature), `shared ${instr.file} must ride the global artifact`)
    assert.ok(
      global.includes(`## ${instr.name}`),
      `shared ${instr.file} must have its section header`,
    )
    assert.ok(
      !project.includes(`## ${instr.name}\n`),
      `shared ${instr.file} must NOT have a section in the project artifact (zero-overlap)`,
    )
    assert.ok(
      !project.includes(signature),
      `shared ${instr.file} body must NOT appear in the project artifact (zero-overlap)`,
    )
  }
})

test('agent-scoped instructions reach only their agents', () => {
  const instructions = readInstructions()
  const scoped = instructions.filter((i) => i.agents.length > 0 && !i.agents.includes('*'))
  assert.ok(scoped.length > 0, 'the fixture expects at least one agent-scoped instruction')
  for (const instr of scoped) {
    const agent = instr.agents[0]
    const promptBody = readFileSync(join(ROOT, 'src', 'agents', `${agent}.md`), 'utf8')
    const prompt = generateAgentPrompt(agent, promptBody, instructions)
    const signature = instr.body
      .split('\n')
      .find((l) => l.trim().length > 0)
      .slice(0, 60)
    assert.ok(prompt.includes(signature), `${instr.file} must ride ${agent}'s prompt`)
    const other = instr.agents.includes('zeus') ? 'aphrodite' : 'zeus'
    const otherBody = readFileSync(join(ROOT, 'src', 'agents', `${other}.md`), 'utf8')
    const otherPrompt = generateAgentPrompt(other, otherBody, instructions)
    assert.ok(
      !otherPrompt.includes(signature),
      `${instr.file} must NOT ride ${other}'s prompt (scoped to ${instr.agents.join(',')})`,
    )
  }
})

test('logicalLineCount counts physical lines deterministically', () => {
  assert.equal(logicalLineCount(''), 0)
  assert.equal(logicalLineCount('a'), 1)
  assert.equal(logicalLineCount('a\n'), 1)
  assert.equal(logicalLineCount('a\nb'), 2)
  assert.equal(logicalLineCount('a\n\nb'), 3)
})
